#!/usr/bin/env python3
"""Generate a parametrised FRR leaf-spine fabric for the scale test (scripts/scale_test.sh).

    scale_topology.py OUT_DIR --leaves N [--leak LEAF] [--timeout SECONDS]

The lab has N leaves + 2 spines (N + 2 nodes: 48 leaves = 50 nodes, 98 leaves = 100 nodes).
Every leaf has one link to each spine and runs eBGP to both. Each leaf announces one LAN prefix, 10.200.<i>.0/24.

  leaf i   AS 65100+i   router-id 10.255.0.i   lo 10.200.i.1/24
  spine s  AS 65000+s-1 router-id 10.255.1.s   (spine1 = AS 65000, spine2 = AS 65001)
  link     spine s <-> leaf i: 10.<s>.<i>.0/30, spine .1 on spine eth<i>, leaf .2 on leaf eth<s>

The guard checks on every leaf: both sessions up, the exact prefix count from spine1 (the other N-1 LANs,
so a leak that adds a prefix breaks it), one route to the next leaf's LAN, no BGP default route. One ping
across the fabric (leaf1 to the last leaf). With --leak LEAF that leaf also originates 0.0.0.0/0 (a static
default to Null0 plus a network statement), which every other leaf must catch: the run must FAIL.
"""
from __future__ import annotations

import argparse
import shutil
import sys
from pathlib import Path

IMAGE = "quay.io/frrouting/frr:10.4.1"
MAX_LEAVES = 250          # the 10.<s>.<i>.0/30 plan and the default 172.20.20.0/24 management network (254 hosts)

DAEMONS = """zebra=yes
bgpd=yes
ospfd=no
ospf6d=no
ripd=no
ripngd=no
isisd=no
pimd=no
ldpd=no
nhrpd=no
eigrpd=no
babeld=no
sharpd=no
staticd=yes
pbrd=no
bfdd=no
fabricd=no
vrrpd=no

vtysh_enable=yes
zebra_options="  -A 127.0.0.1 -s 90000000"
bgpd_options="   -A 127.0.0.1"
staticd_options="-A 127.0.0.1"
"""
VTYSH = "service integrated-vtysh-config\n"


def leaf_conf(i: int, leak: bool) -> str:
    lines = ["frr defaults datacenter", f"hostname leaf{i}", "!", "interface lo", f" ip address 10.200.{i}.1/24", "!"]
    for s in (1, 2):
        lines += [f"interface eth{s}", f" ip address 10.{s}.{i}.2/30", "!"]
    if leak:
        lines += ["ip route 0.0.0.0/0 Null0", "!"]
    lines += [f"router bgp {65100 + i}", f" bgp router-id 10.255.0.{i}"]
    for s in (1, 2):
        lines.append(f" neighbor 10.{s}.{i}.1 remote-as {65000 + s - 1}")
    lines.append(" address-family ipv4 unicast")
    lines.append(f"  network 10.200.{i}.0/24")
    if leak:
        lines.append("  network 0.0.0.0/0")
    for s in (1, 2):
        lines += [f"  neighbor 10.{s}.{i}.1 route-map ALLOW-ALL in", f"  neighbor 10.{s}.{i}.1 route-map ALLOW-ALL out"]
    lines += [" exit-address-family", "!", "route-map ALLOW-ALL permit 10", "!"]
    return "\n".join(lines) + "\n"


def spine_conf(s: int, n: int) -> str:
    lines = ["frr defaults datacenter", f"hostname spine{s}", "!"]
    for i in range(1, n + 1):
        lines += [f"interface eth{i}", f" ip address 10.{s}.{i}.1/30", "!"]
    lines += [f"router bgp {65000 + s - 1}", f" bgp router-id 10.255.1.{s}"]
    for i in range(1, n + 1):
        lines.append(f" neighbor 10.{s}.{i}.2 remote-as {65100 + i}")
    lines.append(" address-family ipv4 unicast")
    for i in range(1, n + 1):
        lines += [f"  neighbor 10.{s}.{i}.2 route-map ALLOW-ALL in", f"  neighbor 10.{s}.{i}.2 route-map ALLOW-ALL out"]
    lines += [" exit-address-family", "!", "route-map ALLOW-ALL permit 10", "!"]
    return "\n".join(lines) + "\n"


def topology(n: int) -> str:
    nodes = ["spine1", "spine2"] + [f"leaf{i}" for i in range(1, n + 1)]
    out = [f"# Generated by scripts/scale_topology.py: {n} leaves + 2 spines = {n + 2} FRR nodes.",
           f"name: ndr-scale{n}", "", "topology:", "  defaults:", "    kind: linux", f"    image: {IMAGE}", "  nodes:"]
    for name in nodes:
        out += [f"    {name}:", "      binds:", "        - configs/daemons:/etc/frr/daemons",
                "        - configs/vtysh.conf:/etc/frr/vtysh.conf", f"        - configs/{name}.conf:/etc/frr/frr.conf"]
    out.append("  links:")
    for i in range(1, n + 1):
        for s in (1, 2):
            out.append(f'    - endpoints: ["spine{s}:eth{i}", "leaf{i}:eth{s}"]')
    return "\n".join(out) + "\n"


def checks(n: int, timeout: int) -> str:
    out = [f"# Generated by scripts/scale_topology.py: guard checks for {n} leaves.", "lab: topology.clab.yml",
           f"timeout: {timeout}   # seconds each positive check may wait for convergence", "", "checks:"]
    for i in range(1, n + 1):
        nxt = i % n + 1
        out += [f"  - {{type: bgp_session, node: leaf{i}, neighbor: 10.1.{i}.1}}",
                f"  - {{type: bgp_session, node: leaf{i}, neighbor: 10.2.{i}.1}}",
                # spine1 sends every other leaf's LAN and nothing else: a leaked prefix breaks the exact count
                f"  - {{type: bgp_prefixes, node: leaf{i}, neighbor: 10.1.{i}.1, min: {n - 1}, max: {n - 1}}}",
                f"  - {{type: route, node: leaf{i}, prefix: 10.200.{nxt}.0/24, protocol: bgp}}",
                f"  - {{type: route, node: leaf{i}, prefix: 0.0.0.0/0, protocol: bgp, present: false}}"]
    if n > 1:
        out.append(f"  - {{type: ping, node: leaf1, source: 10.200.1.1, target: 10.200.{n}.1}}")
    return "\n".join(out) + "\n"


def generate(out: Path, n: int, leak: int | None = None, timeout: int | None = None) -> Path:
    if not 2 <= n <= MAX_LEAVES:
        raise ValueError(f"--leaves must be 2..{MAX_LEAVES}, got {n}")
    if leak is not None and not 1 <= leak <= n:
        raise ValueError(f"--leak must be a leaf number 1..{n}, got {leak}")
    shutil.rmtree(out, ignore_errors=True)
    cfg = out / "configs"
    cfg.mkdir(parents=True)

    def put(path: Path, text: str) -> None:
        path.write_text(text, encoding="utf-8", newline="\n")
    put(cfg / "daemons", DAEMONS)
    put(cfg / "vtysh.conf", VTYSH)
    for s in (1, 2):
        put(cfg / f"spine{s}.conf", spine_conf(s, n))
    for i in range(1, n + 1):
        put(cfg / f"leaf{i}.conf", leaf_conf(i, leak == i))
    put(out / "topology.clab.yml", topology(n))
    put(out / "netdryrun.yml", checks(n, timeout or 180 + 4 * n))
    return out


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("out", type=Path, help="folder to (re)create")
    ap.add_argument("--leaves", type=int, required=True, help="number of leaves; the lab has this + 2 nodes")
    ap.add_argument("--leak", type=int, help="leaf number that also originates a default route (must-fail variant)")
    ap.add_argument("--timeout", type=int, help="per-check convergence timeout (default 180 + 4 s per leaf)")
    a = ap.parse_args(argv)
    try:
        generate(a.out, a.leaves, a.leak, a.timeout)
    except ValueError as e:
        print(f"error: {e}", file=sys.stderr)
        return 2
    print(f"{a.out}: {a.leaves + 2} nodes, {2 * a.leaves} links, {5 * a.leaves + 1} checks"
          + (f", leak at leaf{a.leak}" if a.leak else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main())
