"""Expand an oracle source (oracle.src.yml, written by hand) into oracle.yml: the expected verdict of every check in
the baseline and in every overlay, each with its reason.

    python interop/tools/build_oracle.py L1      # reads interop/L1/oracle.src.yml and base/netdryrun.yml

Source format:
    baseline: {default: {expect, why}, checks: {ID: {expect, why}}}
    overlays:
      ID:
        status: failed | error | passed
        flips: {CHECK: {expect, why}}            # checks whose verdict differs from the baseline
        not_evaluated: {nodes: [...], why: ...}   # every post-convergence check on these nodes fails ("not evaluated")

"Post-convergence" follows the netdryrun.yml reference (written here from the docs, not imported from Netdryrun):
route/bgp_route with present: false; bgp_route with any attribute key; bgp_prefixes with max or exact; bgp_session
with a state other than established; ping with expect: failure.
"""
from __future__ import annotations

import sys
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parents[1]
DIRS = {"L1": ("L1", "L1/base/netdryrun.yml"), "L1s8": ("L1/s8", "L1/s8/netdryrun.yml"),
        "L2": ("L2", "L2/base/netdryrun.yml")}
ATTRS = ("communities", "without_communities", "as_path", "as_path_regex", "local_pref", "med", "next_hop")


def post_convergence(c: dict) -> bool:
    t = c["type"]
    return ((t in ("route", "bgp_route") and c.get("present", True) is False)
            or (t == "bgp_route" and any(k in c for k in ATTRS))
            or (t == "bgp_prefixes" and ("max" in c or "exact" in c))
            or (t == "bgp_session" and c.get("state", "established") != "established")
            or (t == "ping" and c.get("expect", "success") == "failure"))


def expand(lab: str) -> dict:
    src = yaml.safe_load((HERE / DIRS[lab][0] / "oracle.src.yml").read_text(encoding="utf-8"))
    checks = yaml.safe_load((HERE / DIRS[lab][1]).read_text(encoding="utf-8"))["checks"]
    ids = {c["name"].split()[0]: c for c in checks}
    base = {}
    for cid in ids:
        base[cid] = dict(src["baseline"]["checks"].get(cid) or src["baseline"]["default"])
    out = {"lab": lab, "generated_from": f"interop/{DIRS[lab][0]}/oracle.src.yml", "baseline": {"status": src["baseline"]["status"],
           "checks": base}, "overlays": {}, "pairs": src.get("pairs", []), "refusals": src.get("refusals", {})}
    for oid, ov in src["overlays"].items():
        exp = {}
        if ov.get("status") == "error":
            out["overlays"][oid] = {"status": "error", "why": ov["why"], "checks": {}}
            continue
        ne = ov.get("not_evaluated")
        if ne:
            for cid, c in ids.items():
                if c["node"] in ne["nodes"] and post_convergence(c):
                    exp[cid] = {"expect": "fail", "why": f"not evaluated: {ne['why']}"}
        for cid, f in (ov.get("flips") or {}).items():
            if cid not in ids:
                raise SystemExit(f"{lab} {oid}: unknown check {cid}")
            if cid in exp and f["expect"] != "fail":
                raise SystemExit(f"{lab} {oid}: {cid} is post-convergence on a not-evaluated node, cannot {f['expect']}")
            exp.setdefault(cid, f)
        full = {}
        for cid in ids:
            full[cid] = exp.get(cid) or {"expect": base[cid]["expect"], "why": "unchanged from the baseline"}
        changed = sorted(cid for cid in ids if full[cid]["expect"] != base[cid]["expect"])
        out["overlays"][oid] = {"status": ov["status"], "flips": changed, "checks": full}
    return out


if __name__ == "__main__":
    lab = sys.argv[1]
    data = expand(lab)
    header = (f"# GENERATED by interop/tools/build_oracle.py from interop/{DIRS[lab][0]}/oracle.src.yml: do not edit by hand.\n"
              "# Expected verdict (pass/fail) of every check in the baseline and in every overlay, with the reason.\n"
              "# `flips` lists the checks whose verdict differs from the baseline: any other flip is a finding.\n")
    (HERE / DIRS[lab][0] / "oracle.yml").write_bytes((header + yaml.safe_dump(data, sort_keys=False, width=140)).encode())
    for oid, ov in data["overlays"].items():
        print(oid, ov["status"], len(ov.get("flips", [])), "flips")
