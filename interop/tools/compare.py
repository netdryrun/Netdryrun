"""Compare Netdryrun JSON reports with the pre-registered oracle.

    python interop/tools/compare.py L1 [L1s8 L2 ...]     # reads interop/results/<lab>/*.json, writes results/SUMMARY.md

A report file is named <variant>-<mode>-<n>.json (variant: base or an overlay ID; mode: fresh or reapply). Each check
is matched by the ID that starts its name. A check whose verdict differs from the oracle is a mismatch:
  BLOCKER-class  passed where the oracle says fail (a false pass)
  MAJOR-class    failed where the oracle says pass
and a run whose status differs (error vs failed vs passed) is listed too. Severity is final only after the evidence
is read (an oracle line resting on a NOS assumption can be the wrong side).
"""
from __future__ import annotations

import json
import re
import sys
from collections import defaultdict
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parents[1]
ORACLES = {"L1": "L1/oracle.yml", "L1s8": "L1/s8/oracle.yml", "L2": "L2/oracle.yml"}
NAME = re.compile(r"^(?P<variant>[A-Za-z0-9]+)-(?P<mode>fresh|reapply|refusal)-(?P<n>[\w]+)\.json$")


def expected(oracle: dict, variant: str) -> dict:
    if variant.startswith("refuse"):
        r = oracle["refusals"][variant[len("refuse"):]]
        return {"status": "error", "checks": {}, "why": r["why"]}
    return oracle["baseline"] if variant == "base" else oracle["overlays"][variant]


def compare_run(oracle: dict, variant: str, report: dict) -> dict:
    exp = expected(oracle, variant)
    got = {c["name"].split()[0]: c for c in report.get("checks", [])}
    mism = []
    for cid, e in exp.get("checks", {}).items():
        c = got.get(cid)
        if c is None:
            if report.get("status") != "error" or exp["status"] != "error":
                mism.append({"check": cid, "expect": e["expect"], "actual": "not run", "detail": "", "why": e["why"]})
            continue
        actual = "pass" if c["passed"] else "fail"
        if e["expect"] == "either":
            continue
        if actual != e["expect"]:
            mism.append({"check": cid, "expect": e["expect"], "actual": actual, "detail": c.get("detail", ""),
                         "why": e["why"], "class": "BLOCKER" if actual == "pass" else "MAJOR"})
    for pair in oracle.get("pairs", []):
        if all(exp.get("checks", {}).get(c, {}).get("expect") == "either" for c in pair) and all(c in got for c in pair):
            n = sum(bool(got[c]["passed"]) for c in pair)
            if n != 1:
                mism.append({"check": "+".join(pair), "expect": "exactly one pass", "actual": f"{n} passed",
                             "detail": "; ".join(str(got[c].get("detail", ""))[:120] for c in pair),
                             "why": "pair rule", "class": "BLOCKER" if n > 1 else "MAJOR"})
    return {"status": report.get("status"), "expected_status": exp["status"], "error": report.get("error"),
            "mismatches": mism, "checks": len(got)}


def main(labs: list[str]) -> None:
    lines = ["# Interop results: oracle vs actual", "",
             "Generated by `interop/tools/compare.py` from the JSON reports in `interop/results/` (not committed: large).",
             "A mismatch is classed BLOCKER when a check passed where the oracle says fail, MAJOR when it failed where the",
             "oracle says pass. The report (`research/interop/REPORT.md`) says which mismatches are Netdryrun findings and",
             "which are oracle lines that rested on a wrong NOS assumption.", ""]
    for lab in labs:
        oracle = yaml.safe_load((HERE / ORACLES[lab]).read_text(encoding="utf-8"))
        runs = defaultdict(list)
        for f in sorted((HERE / "results" / lab).glob("*.json")):
            m = NAME.match(f.name)
            if not m:
                continue
            runs[m["variant"]].append((m["mode"], m["n"], json.loads(f.read_text(encoding="utf-8"))))
        lines += [f"## {lab}", "", "| Variant | Run | Status (expected) | Checks | Mismatches |", "|---|---|---|---|---|"]
        detail = []
        order = ["base"] + list(oracle["overlays"]) + [f"refuse{r}" for r in oracle.get("refusals", {})]
        for variant in order:
            for mode, n, rep in runs.get(variant, []):
                r = compare_run(oracle, variant, rep)
                ok_status = r["status"] == r["expected_status"]
                mm = ", ".join(f"{x['check']}({x['actual']})" for x in r["mismatches"]) or "none"
                st = f"{r['status']}" + ("" if ok_status else f" (**expected {r['expected_status']}**)")
                lines.append(f"| {variant} | {mode} {n} | {st} | {r['checks']} | {mm} |")
                for x in r["mismatches"]:
                    detail.append(f"- {variant} {mode} {n} **{x['check']}**: oracle {x['expect']} ({x['why']}); "
                                  f"actual {x['actual']}: {str(x['detail'])[:300]}")
                if r["error"]:
                    detail.append(f"- {variant} {mode} {n} error: {str(r['error'])[:300]}")
            if variant not in runs:
                lines.append(f"| {variant} | not run | | | |")
        lines += ["", "### Mismatch details", ""] + (detail or ["none"]) + [""]
    (HERE / "results" / "SUMMARY.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main(sys.argv[1:] or ["L1", "L1s8", "L2"])
